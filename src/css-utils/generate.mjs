import { calculateClamp, checkWCAG } from "utopia-core";

/**
 * @typedef {{ name: string, min: number, max: number }} FluidToken sizes in px
 * @typedef {{ name: string, light?: string, dark?: string, value?: string, textUtility?: boolean }} ColorToken
 * @typedef {{ name: string, value: string[] }} FontToken
 */

export class WcagError extends Error {
  /** @param {string[]} flagged */
  constructor(flagged) {
    super(
      `WCAG 1.4.4 (resize text) flagged these type steps:\n${flagged.join("\n")}`,
    );
    this.name = "WcagError";
  }
}

/** @param {string} name */
const slug = (name) =>
  name
    .trim()
    .toLowerCase()
    .replace(/\s*-\s*/g, "-")
    .replace(/\s+/g, "-");

/** @param {number} n */
const rem = (n) => `${Math.round((n / 16) * 10000) / 10000}rem`;

/**
 * Fluid value in rem and vi (Utopia's `viewport` mode), or plain rem when flat.
 * @param {FluidToken} token
 * @param {{ min: number, max: number }} viewports
 */
function fluid({ min, max }, viewports) {
  if (min === max) return rem(min);
  return calculateClamp({
    minSize: min,
    maxSize: max,
    minWidth: viewports.min,
    maxWidth: viewports.max,
    relativeTo: "viewport",
  });
}

const generic = new Set([
  "serif",
  "sans-serif",
  "monospace",
  "system-ui",
  "ui-monospace",
  "ui-serif",
  "ui-sans-serif",
]);

/** @param {string} family */
const family = (family) => (generic.has(family) ? family : `"${family}"`);

/**
 * Tokens in, CSS out. Pure: reads and writes nothing.
 * @param {{
 *   viewports: { min: number, max: number },
 *   textSizes: { items: FluidToken[] },
 *   spacing: { items: FluidToken[] },
 *   colors: { items: ColorToken[] },
 *   fonts: { items: FontToken[] },
 * }} tokens
 */
export function generate({ viewports, textSizes, spacing, colors, fonts }) {
  // Only type is text, so only type is checked for WCAG 1.4.4.
  const flagged = textSizes.items.flatMap(({ name, min, max }) => {
    const range = checkWCAG({
      min,
      max,
      minWidth: viewports.min,
      maxWidth: viewports.max,
    });
    // checkWCAG returns [] or null when the step passes.
    return range?.length
      ? [
          `  ${name}: fails between ${Math.round(range[0])}px and ${Math.round(range[1])}px viewports`,
        ]
      : [];
  });
  if (flagged.length > 0) throw new WcagError(flagged);

  const props = [];
  for (const c of colors.items) {
    const value = c.value ?? `light-dark(${c.light}, ${c.dark})`;
    props.push(`--color-${slug(c.name)}: ${value};`);
  }
  for (const f of fonts.items) {
    props.push(`--font-${slug(f.name)}: ${f.value.map(family).join(", ")};`);
  }
  for (const t of textSizes.items) {
    props.push(`--size-${slug(t.name)}: ${fluid(t, viewports)};`);
  }
  for (const t of spacing.items) {
    props.push(`--space-${slug(t.name)}: ${fluid(t, viewports)};`);
  }

  const header =
    "/* Generated by src/css-utils/build-tokens.mjs. Do not edit. */";
  const tokensCss = `${header}\n:root {\n${props.map((p) => `  ${p}`).join("\n")}\n}\n`;

  const rules = [];
  const rule = (selector, declaration) =>
    rules.push(`${selector} {\n  ${declaration}\n}`);
  for (const t of spacing.items) {
    const n = slug(t.name);
    rule(`.flow-space-${n}`, `--flow-space: var(--space-${n});`);
    rule(`.gutter-${n}`, `--gutter: var(--space-${n});`);
    rule(`.region-space-${n}`, `--region-space: var(--space-${n});`);
  }
  for (const c of colors.items) {
    const n = slug(c.name);
    if (c.textUtility !== false)
      rule(`.text-${n}`, `color: var(--color-${n});`);
    rule(`.bg-${n}`, `background-color: var(--color-${n});`);
  }
  const utilitiesCss = `${header}\n${rules.join("\n\n")}\n`;

  return { tokensCss, utilitiesCss };
}
